#require_once 'Zend/Pdf/Element.php';
/**
 * PDF file 'indirect object' element implementation
 *
 * @category   Zend
 * @package    Zend_Pdf
 * @copyright  Copyright (c) 2005-2015 Zend Technologies USA Inc. (http://www.zend.com)
 * @license    http://framework.zend.com/license/new-bsd     New BSD License
 */
class Zend_Pdf_Element_Object extends Zend_Pdf_Element
{
    /**
     * Object value
     *
     * @var Zend_Pdf_Element
     */
    protected $_value;
    /**
     * Object number within PDF file
     *
     * @var integer
     */
    protected $_obj_num;
    /**
     * Generation number
     *
     * @var integer
     */
    protected $_gen_num;
    /**
     * Reference to the factory.
     *
     * @var Zend_Pdf_ElementFactory
     */
    protected $_factory;
    /**
     * Object constructor
     *
     * @param integer $objNum
     * @param integer $genNum
     * @throws Zend_Pdf_Exception
     */
    public function __construct(Zend_Pdf_Element $val, $obj_num, $gen_num, Zend_pdf_element_Factory $factory)
    {
        if ($val instanceof self) {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Object number must not be an instance of Zend_Pdf_Element_Object.');
        }
        if (!(is_integer($obj_num) && $obj_num > 0)) {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Object number must be positive integer.');
        }
        if (!(is_integer($gen_num) && $gen_num >= 0)) {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Generation number must be non-negative integer.');
        }
        $this->_value = $val;
        $this->_obj_num = $obj_num;
        $this->_gen_num = $gen_num;
        $this->_factory = $factory;
        $this->set_parent_object($this);
        $factory->register_object($this, $obj_num . ' ' . $gen_num);
    }
    /**
     * Check, that object is generated by specified factory
     *
     * @return Zend_Pdf_ElementFactory
     */
    public function get_factory()
    {
        return $this->_factory;
    }
    /**
     * Return type of the element.
     *
     * @return integer
     */
    public function get_type()
    {
        return $this->_value->get_type();
    }
    /**
     * Get object number
     *
     * @return integer
     */
    public function get_obj_num()
    {
        return $this->_obj_num;
    }
    /**
     * Get generation number
     *
     * @return integer
     */
    public function get_gen_num()
    {
        return $this->_gen_num;
    }
    /**
     * Return reference to the object
     *
     * @param Zend_Pdf_Factory $factory
     */
    public function to_string($factory = null): string
    {
        if ($factory === null) {
            $shift = 0;
        } else {
            $shift = $factory->get_enumeration_shift($this->_factory);
        }
        return $this->_obj_num + $shift . ' ' . $this->_gen_num . ' R';
    }
    /**
     * Dump object to a string to save within PDF file.
     *
     * $factory parameter defines operation context.
     */
    public function dump(Zend_pdf_element_Factory $factory): string
    {
        $shift = $factory->get_enumeration_shift($this->_factory);
        return $this->_obj_num + $shift . ' ' . $this->_gen_num . " obj \n" . $this->_value->to_string($factory) . "\n" . "endobj\n";
    }
    /**
     * Get handler
     *
     * @return mixed
     */
    public function __get(string $property)
    {
        return $this->_value->{$property};
    }
    /**
     * Set handler
     *
     * @param  mixed $value
     */
    public function __set(string $property, $value)
    {
        $this->_value->{$property} = $value;
    }
    /**
     * Call handler
     *
     * @param array  $args
     * @return mixed
     */
    public function __call(string $method, array $args)
    {
        return call_user_func_array([$this->_value, $method], $args);
    }
    /**
     * Detach PDF object from the factory (if applicable), clone it and attach to new factory.
     *
     * @param Zend_Pdf_ElementFactory $factory  The factory to attach
     * @param array &$processed  List of already processed indirect objects, used to avoid objects duplication
     * @param integer $mode  Cloning mode (defines filter for objects cloning)
     * @returns Zend_Pdf_Element
     */
    public function make_clone(Zend_pdf_element_Factory $factory, array &$processed, $mode)
    {
        $id = spl_object_hash($this);
        if (isset($processed[$id])) {
            // Do nothing if object is already processed
            // return it
            return $processed[$id];
        }
        // Create obect with null value and register it in $processed container
        $processed[$id] = $cloned_object = $factory->new_object(new Zend_Pdf_Element_Null());
        // Pecursively process actual data
        $cloned_object->_value = $this->_value->make_clone($factory, $processed, $mode);
        if ($cloned_object->_value instanceof Zend_Pdf_Element_Null) {
            // Do not store null objects within $processed container since it may be filtered
            // by $mode parameter but used in some future pass
            unset($processed[$id]);
            // Return direct null object
            return $cloned_object->_value;
        }
        return $cloned_object;
    }
    /**
     * Mark object as modified, to include it into new PDF file segment
     */
    public function touch()
    {
        $this->_factory->mark_as_modified($this);
    }
    /**
     * Return object, which can be used to identify object and its references identity
     */
    public function get_object(): self
    {
        return $this;
    }
    /**
     * Clean up resources, used by object
     */
    public function clean_up()
    {
        $this->_value = null;
    }
    /**
     * Convert PDF element to PHP type.
     *
     * @return mixed
     */
    public function to_php()
    {
        return $this->_value->to_php();
    }
}