#require_once 'Zend/Pdf/Element/Null.php';
/** Zend_Pdf_Element */
#require_once 'Zend/Pdf/Element.php';
/**
 * PDF file 'reference' element implementation
 *
 * @category   Zend
 * @package    Zend_Pdf
 * @copyright  Copyright (c) 2005-2015 Zend Technologies USA Inc. (http://www.zend.com)
 * @license    http://framework.zend.com/license/new-bsd     New BSD License
 */
class Zend_Pdf_Element_Reference extends Zend_Pdf_Element
{
    /**
     * Object value
     * The reference to the object
     *
     * @var mixed
     */
    private $_ref;
    /**
     * Object number within PDF file
     *
     * @var integer
     */
    private $_obj_num;
    /**
     * Generation number
     *
     * @var integer
     */
    private $_gen_num;
    /**
     * Reference context
     *
     * @var Zend_Pdf_Element_Reference_Context
     */
    private $_context;
    /**
     * Reference to the factory.
     *
     * It's the same as referenced object factory, but we save it here to avoid
     * unnecessary dereferencing, whech can produce cascade dereferencing and parsing.
     * The same for duplication of getFactory() function. It can be processed by __call()
     * method, but we catch it here.
     *
     * @var Zend_Pdf_ElementFactory
     */
    private $_factory;
    /**
     * Object constructor:
     *
     * @param int $objNum
     * @param int $genNum
     * @throws Zend_Pdf_Exception
     */
    public function __construct($obj_num, $gen_num, Zend_Pdf_Element_Reference_Context $context, Zend_pdf_element_Factory $factory)
    {
        if (!(is_integer($obj_num) && $obj_num > 0)) {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Object number must be positive integer');
        }
        if (!(is_integer($gen_num) && $gen_num >= 0)) {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Generation number must be non-negative integer');
        }
        $this->_obj_num = $obj_num;
        $this->_gen_num = $gen_num;
        $this->_ref = null;
        $this->_context = $context;
        $this->_factory = $factory;
    }
    /**
     * Check, that object is generated by specified factory
     *
     * @return Zend_Pdf_ElementFactory
     */
    public function get_factory()
    {
        return $this->_factory;
    }
    /**
     * Return type of the element.
     *
     * @return integer
     */
    public function get_type()
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        return $this->_ref->get_type();
    }
    /**
     * Return reference to the object
     *
     * @param Zend_Pdf_Factory $factory
     */
    public function to_string($factory = null): string
    {
        if ($factory === null) {
            $shift = 0;
        } else {
            $shift = $factory->get_enumeration_shift($this->_factory);
        }
        return $this->_obj_num + $shift . ' ' . $this->_gen_num . ' R';
    }
    /**
     * Dereference.
     * Take inderect object, take $value member of this object (must be Zend_Pdf_Element),
     * take reference to the $value member of this object and assign it to
     * $value member of current PDF Reference object
     * $obj can be null
     *
     * @throws Zend_Pdf_Exception
     */
    private function _dereference()
    {
        if (($obj = $this->_factory->fetch_object($this->_obj_num . ' ' . $this->_gen_num)) === null) {
            $obj = $this->_context->get_parser()->get_object($this->_context->get_ref_table()->get_offset($this->_obj_num . ' ' . $this->_gen_num . ' R'), $this->_context);
        }
        if ($obj === null) {
            $this->_ref = new Zend_Pdf_Element_Null();
            return;
        }
        if ($obj->to_string() != $this->_obj_num . ' ' . $this->_gen_num . ' R') {
            #require_once 'Zend/Pdf/Exception.php';
            throw new Zend_Pdf_Exception('Incorrect reference to the object');
        }
        $this->_ref = $obj;
    }
    /**
     * Detach PDF object from the factory (if applicable), clone it and attach to new factory.
     *
     * @param Zend_Pdf_ElementFactory $factory  The factory to attach
     * @param array &$processed  List of already processed indirect objects, used to avoid objects duplication
     * @param integer $mode  Cloning mode (defines filter for objects cloning)
     * @returns Zend_Pdf_Element
     */
    public function make_clone(Zend_pdf_element_Factory $factory, array &$processed, $mode)
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        // This code duplicates code in Zend_Pdf_Element_Object class,
        // but allows to avoid unnecessary method call in most cases
        $id = spl_object_hash($this->_ref);
        return $processed[$id] ?? $this->_ref->make_clone($factory, $processed, $mode);
    }
    /**
     * Mark object as modified, to include it into new PDF file segment.
     */
    public function touch()
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        $this->_ref->touch();
    }
    /**
     * Return object, which can be used to identify object and its references identity
     *
     * @return Zend_Pdf_Element_Object
     */
    public function get_object()
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        return $this->_ref;
    }
    /**
     * Get handler
     *
     * @return mixed
     */
    public function __get(string $property)
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        return $this->_ref->{$property};
    }
    /**
     * Set handler
     *
     * @param  mixed $value
     */
    public function __set(string $property, $value)
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        $this->_ref->{$property} = $value;
    }
    /**
     * Call handler
     *
     * @param array  $args
     * @return mixed
     */
    public function __call(string $method, array $args)
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        return call_user_func_array([$this->_ref, $method], $args);
    }
    /**
     * Clean up resources
     */
    public function clean_up()
    {
        $this->_ref = null;
    }
    /**
     * Convert PDF element to PHP type.
     *
     * @return mixed
     */
    public function to_php()
    {
        if ($this->_ref === null) {
            $this->_dereference();
        }
        return $this->_ref->to_php();
    }
}